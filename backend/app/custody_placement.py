"""Розміщення серійного екземпляра на складі — одне місце для цього присвоєння.

`current_warehouse_id` денормалізований із рухів, а точка зберігання належить
КОНКРЕТНОМУ складу, тож при переїзді на інший склад вона більше не має сенсу і
скидається. Тримаємо це в одній функції, щоб жоден шлях (рух, накладна, відкат,
імпорт) не забув про скидання.
"""


def place_instance(inst, warehouse_id) -> None:
    """Поставити екземпляр на склад (None = списано/ніде); зміна складу скидає точку."""
    if inst.current_warehouse_id != warehouse_id:
        inst.storage_point_id = None
    inst.current_warehouse_id = warehouse_id
